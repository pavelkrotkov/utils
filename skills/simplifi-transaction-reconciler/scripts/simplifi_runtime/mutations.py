"""Provider mutations: what may be written, on whose say-so, and how it is undone.

This is the first part of the runtime that can change a live financial account,
and it is built so that every step a person would want to audit afterwards
happened on purpose and left a record.

Four rules shape everything here.

**A decision is not an authorization.** `decide` records judgment and says so:
its action vocabulary has no write in it, and a recorded decision is a terminal
artifact for review. A mutation reads those records as *input* — the category to
set comes from the store, never from a proposal file — and then requires a
separate, explicit human authorization naming who is asking and why.

**Dry run is the default and describes the real request.** The rendering below
is produced from the same `PlannedMutation` objects `apply_plan` executes, and
names the endpoint, the transaction, the field, and both values. A preview
generated by different code from the thing it previews is a preview of nothing.

**The provider is re-read immediately before the write.** A plan is built from
the local snapshot, which is by definition a statement about the past. Between
planning and writing, a transaction can be recategorized in the app, deleted, or
replaced. Every one of those makes the plan wrong in a way only the provider
knows, so the live document is fetched, checked field by field against what was
planned, and refused if it moved.

**Only verified endpoints are callable.** The capability registry below carries
every mutation this project has considered, including the ones it will not
perform, with the reason. `transaction_category` is available because the
request shape, the job envelope and the polling endpoint were captured against
the live app. Rule writes are not, because no rule endpoint was ever observed
and the semantics of a contains-style match operator are unverified — see the
[API reference](../../references/simplifi-api.md).
"""

from __future__ import annotations

import copy
import json
import time
import uuid
from collections.abc import Callable, Iterable, Mapping, Sequence
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any

#: Recorded verdict + action pair that makes a category write eligible. A
#: proposal is only ever a candidate; this is the reviewer having accepted it.
ELIGIBLE_DECISION = "accept"
ELIGIBLE_ACTION = "record_category_proposal"

#: Seconds between writes. The provider publishes a manual-refresh rate limit
#: but nothing about write rates, so this is deliberately conservative: a burst
#: that trips an undocumented limit fails partway through a batch, which is the
#: worst shape a batch of financial writes can fail in.
WRITE_INTERVAL_SECONDS = 1.0

#: How long to wait for a write job to settle, and how often to ask.
JOB_TIMEOUT_SECONDS = 30.0
JOB_POLL_SECONDS = 1.0

#: Job statuses that mean the provider finished the work.
JOB_SUCCESS_STATUSES = frozenset({"success", "succeeded", "complete", "completed", "done"})
JOB_FAILURE_STATUSES = frozenset({"failed", "failure", "error", "rejected", "cancelled"})

OUTCOME_SUCCEEDED = "succeeded"
OUTCOME_FAILED = "failed"
OUTCOME_UNKNOWN = "unknown"


class MutationError(RuntimeError):
    """A mutation could not be planned, authorized, or carried out."""


class AuthorizationError(MutationError):
    """The runtime was asked to write without an explicit human authorization."""


class PreconditionError(MutationError):
    """The world moved between planning and writing."""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


# --- capabilities -----------------------------------------------------------


@dataclass(frozen=True)
class MutationCapability:
    """One thing the runtime could do to a live account, and what it costs.

    Registered whether or not it is available. A capability that is refused for
    a reason nobody wrote down gets re-proposed every few months; one that
    carries its reason is a decision that stays decided.
    """

    name: str
    summary: str
    method: str
    path: str
    #: How the endpoint's behavior is known. Only `verified` may be called.
    evidence: str
    #: What this changes beyond the field named, and what it cannot undo.
    risk: str
    #: How far a mistake reaches: one transaction, one account, everything.
    blast_radius: str
    #: Whether the runtime can restore the prior state itself.
    reversible: bool
    available: bool
    #: Why not, when it is not.
    unavailable_because: str = ""


